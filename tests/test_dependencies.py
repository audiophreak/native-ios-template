"""Pins, resolved state, the contract copy and the committed generated client."""

from __future__ import annotations

import datetime
import hashlib
import json
import re
from pathlib import Path

from conftest import TEMPLATE_ROOT

IOS = TEMPLATE_ROOT / "template/ios"
REFERENCE = datetime.date(2026, 11, 18)
CUTOFF = REFERENCE - datetime.timedelta(days=14)
DOC = (TEMPLATE_ROOT / "docs/dependencies.md").read_text()
ROW = re.compile(r"^\| ([A-Za-z-]+) \| (\d+\.\d+\.\d+) \| (\d{4}-\d{2}-\d{2}) \| ([A-Za-z0-9.-]+)", re.M)
TABLE = {name: (version, datetime.date.fromisoformat(released), licence) for name, version, released, licence in ROW.findall(DOC)}


def pins(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text())
    return {pin["identity"]: pin["state"]["version"] for pin in data["pins"]}


def table_pins() -> dict[str, str]:
    return {name.lower(): version for name, (version, _, _) in TABLE.items()}


def test_every_pin_is_at_least_two_weeks_old_and_has_an_allowed_licence() -> None:
    assert len(TABLE) == 10
    for name, (version, released, licence) in TABLE.items():
        assert released <= CUTOFF, f"{name} {version} was released {released}, after the cutoff {CUTOFF}"
        assert licence in {"Apache-2.0", "MIT"}, name


def test_the_manifests_pin_exactly_and_agree_with_the_table() -> None:
    app = (IOS / "Packages/AppCore/Package.swift").read_text()
    tool = (IOS / "Tools/Generator/Package.swift").read_text()
    declared = dict(re.findall(r'\.package\(url: "[^"]*/([A-Za-z-]+?)(?:\.git)?", exact: "([0-9.]+)"\)', app + tool))
    assert declared == {n: TABLE[n][0] for n in declared} and set(declared) == {"swift-openapi-runtime", "swift-openapi-urlsession", "swift-http-types", "swift-collections", "swift-openapi-generator"}
    for text in (app, tool):
        assert not re.search(r"from:|\.upToNext|branch:|revision:|\.package\(path", text.replace(".package(path: \"../", ""))
        assert text.count(".package(url:") == text.count("exact:")


def test_the_resolved_files_hold_exactly_the_tabled_versions_and_agree_with_each_other() -> None:
    app = pins(IOS / "Packages/AppCore/Package.resolved")
    project = pins(IOS / "App.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved")
    tool = pins(IOS / "Tools/Generator/Package.resolved")
    assert app == project, "the Xcode project and the package must resolve to the same versions"
    assert set(app) == {"swift-openapi-runtime", "swift-openapi-urlsession", "swift-http-types", "swift-collections"}
    assert set(tool) == {"swift-openapi-generator", "openapikit", "swift-argument-parser", "yams", "swift-algorithms", "swift-numerics"}
    for resolved in (app, tool):
        for identity, version in resolved.items():
            assert table_pins()[identity] == version, identity


def test_no_dependency_brings_a_build_tool_plugin_into_the_app_build() -> None:
    for manifest in ("Packages/AppCore/Package.swift", "App.xcodeproj/project.pbxproj"):
        text = (IOS / manifest).read_text()
        assert "plugins:" not in text and "OpenAPIGenerator" not in text and "XCSwiftPackageProductDependency" in (text if "pbxproj" in manifest else "XCSwiftPackageProductDependency")


def test_the_contract_copy_matches_its_checksum_and_the_recorded_web_contract() -> None:
    contract = (IOS / "Contract/openapi.json").read_bytes()
    assert (IOS / "Contract/openapi.sha256").read_text().strip() == hashlib.sha256(contract).hexdigest()
    reference = json.loads((TEMPLATE_ROOT / "tools/web_contract.json").read_text())
    assert reference["sha256"] == hashlib.sha256(contract).hexdigest(), "ios/Contract/openapi.json is not the recorded web contract"
    document = json.loads(contract)
    assert document["openapi"].startswith("3.1") and document["info"]["version"].startswith("1.")


def test_the_generator_configuration_is_explicit() -> None:
    config = (IOS / "Contract/openapi-generator-config.yaml").read_text()
    assert "- types" in config and "- client" in config and "accessModifier: public" in config
    assert "plugin" not in config.lower()


def test_the_generated_client_is_committed_and_marked_generated() -> None:
    sources = sorted((IOS / "Packages/AppCore/Sources/APIClient").glob("*.swift"))
    assert [p.name for p in sources] == sorted(["Client.swift", "Types.swift", "Types+Components.swift", "Types+Components+Headers.swift", "Types+Components+Parameters.swift", "Types+Components+RequestBodies.swift", "Types+Components+Responses.swift", "Types+Components+Schemas.swift", "Types+Operations.swift"])
    for source in sources:
        assert source.read_text().startswith("// Generated by swift-openapi-generator, do not modify.")


def test_the_pbxproj_generator_output_is_what_is_committed() -> None:
    import subprocess, sys

    result = subprocess.run([sys.executable, str(TEMPLATE_ROOT / "tools/gen_pbxproj.py"), "--check"], capture_output=True, text=True)
    assert result.returncode == 0, result.stderr


def test_the_project_is_static_and_uses_synchronized_folders_and_the_local_package() -> None:
    project = (IOS / "App.xcodeproj/project.pbxproj").read_text()
    assert "{{" not in project and "{%" not in project
    assert project.count("PBXFileSystemSynchronizedRootGroup;") == 2 and "XCLocalSwiftPackageReference" in project
    assert "DEVELOPMENT_TEAM" not in project and "PROVISIONING_PROFILE" not in project and "CODE_SIGN_IDENTITY" not in project
    assert 'TEST_HOST = "$(BUILT_PRODUCTS_DIR)/App.app/App";' in project
    assert (IOS / "App.xcodeproj/xcshareddata/xcschemes/App.xcscheme").is_file()
