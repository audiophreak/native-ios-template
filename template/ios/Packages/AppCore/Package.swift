// swift-tools-version: 6.0
import PackageDescription

// Everything the app needs that is not user interface: the generated API client (APIClient), and the
// configuration, authentication, Keychain storage and models around it (AppCore). Versions are exact and the
// resolved state is committed (Package.resolved); see ios/AGENTS.md before changing either.
let package = Package(
    name: "AppCore",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
        .library(name: "AppCore", targets: ["AppCore"]),
        .library(name: "APIClient", targets: ["APIClient"]),
    ],
    dependencies: [
        .package(url: "https://github.com/apple/swift-openapi-runtime", exact: "1.13.4"),
        .package(url: "https://github.com/apple/swift-openapi-urlsession", exact: "1.4.0"),
        // Used directly by the bearer middleware.
        .package(url: "https://github.com/apple/swift-http-types", exact: "1.8.0"),
        // Not used directly: pinned so the dependency the URLSession transport brings in is a release at least two
        // weeks old (1.7.6 was newer than that when this was chosen). Raise it deliberately, with its release date.
        .package(url: "https://github.com/apple/swift-collections", exact: "1.7.5"),
    ],
    targets: [
        // Generated by ios/scripts/generate-client.sh from ios/Contract/openapi.json. Never edited by hand.
        .target(
            name: "APIClient",
            dependencies: [.product(name: "OpenAPIRuntime", package: "swift-openapi-runtime")]
        ),
        .target(
            name: "AppCore",
            dependencies: [
                "APIClient",
                .product(name: "OpenAPIRuntime", package: "swift-openapi-runtime"),
                .product(name: "OpenAPIURLSession", package: "swift-openapi-urlsession"),
                .product(name: "HTTPTypes", package: "swift-http-types"),
                .product(name: "DequeModule", package: "swift-collections"),
            ]
        ),
        .testTarget(
            name: "AppCoreTests",
            dependencies: ["AppCore", "APIClient"]
        ),
    ]
)
